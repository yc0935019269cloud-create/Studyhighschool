"""組裝「聊天學完第4單元」頁：把 _src/chat/<subject>-4-N.html 對話片段接成一篇，再用 individual_unit.build 套版。

用法：python _src/build_chat_4.py earth|biology
對話片段由各小節分開寫；改內容請改 _src/chat/ 下的片段，再重跑本腳本。
"""
import json,re,sys,html
from pathlib import Path
from PIL import Image
SRC=Path(__file__).resolve().parent;ROOT=SRC.parent
sys.path.insert(0,str(SRC))
from individual_unit import build

CONF={
 'earth':{'parts':4,'title':'聊天學完第4單元：大氣','chapter':'第4單元 大氣','label':'地球科學','shell':'u4-4.html','source':'地科2','offset':102,
  'prev':['u4-考.html','4-考 考點教學：考試會怎麼問'],'next':['u5-1.html','5-1 海水性質與波浪']},
 'biology':{'parts':5,'title':'聊天學完第4單元：分子生物學','chapter':'第4單元 分子生物學','label':'生物','shell':'u3-5.html','source':'生物2','offset':110,
  'prev':['u4-考.html','4-考 考點教學：考試會怎麼問'],'next':['u5-1.html','5-1 生命的起源']},
}
LINE=re.compile(r'^(<h3 class="chat-topic">.*</h3>|<div class="msg [ts]">.*</div>|\[\[圖:[^|\]]+\|[^\]]+\]\]|<details class="try"><summary>.*</summary><div class="try-a">.*</div></details>)$')

def figure(subject,key,cap):
 p=ROOT/subject/'img'/(key+'.webp');assert p.exists(),'missing image '+key
 w,h=Image.open(p).size
 return ('<figure class="fig authored-figure chat-fig"><img class="figimg" src="img/'+p.name+'" width="'+str(w)+'" height="'+str(h)+'" loading="lazy" alt="'
  +html.escape(cap,quote=True)+'"><figcaption>'+cap+'<span>點圖放大</span></figcaption></figure>')

def main(subject):
 c=CONF[subject];body=[];sections=[];bubbles=tries=0
 body.append('<aside class="box box-concept"><div class="box-h">怎麼讀這頁</div><ol><li>這頁用老師和學生聊天的方式，從頭講完整個第4單元，內容和各篇講義相同。</li><li>看到「換你」先自己想，再點開看答案。</li><li>想看完整表格、原題與詳解，再回各篇講義。</li></ol></aside>')
 for n in range(1,c['parts']+1):
  key=subject+'-4-'+str(n)
  meta=json.loads((SRC/'units'/(key+'.json')).read_text(encoding='utf-8'))
  frag=(SRC/'chat'/(key+'.html')).read_text(encoding='utf-8')
  sections.append('4-'+str(n)+' '+meta['title'].split('：')[0])
  out=[]
  for i,line in enumerate(l.strip() for l in frag.splitlines()):
   if not line:continue
   assert LINE.match(line),key+' 第'+str(i+1)+'行格式不符：'+line[:60]
   assert not re.search(r'style=|<script|\?\?\?|�',line),key+' 禁用內容：'+line[:60]
   m=re.match(r'\[\[圖:([^|\]]+)\|([^\]]+)\]\]',line)
   if m:line=figure(subject,m[1].strip(),m[2].strip())
   bubbles+=line.startswith('<div class="msg');tries+=line.startswith('<details class="try"')
   out.append(line)
  body.append('<h2 class="section" id="s'+str(n)+'">'+meta['id']+' '+meta['title']+'</h2>')
  body.append('<div class="chat">\n'+'\n'.join(out)+'\n</div>')
  body.append('<p class="chat-more"><a href="u'+meta['id']+'.html">想看這篇的完整講義、原題與詳解 → '+meta['id']+'</a></p>')
 ukey=subject+'-4-聊'
 conf={'subject':subject,'id':'4-聊','title':c['title'],'subject_label':c['label'],'chapter':c['chapter'],'shell':c['shell'],'source':c['source'],'offset':c['offset'],
  'pages':[1],'source_note':'內容依第4單元各篇講義改寫成對話。','sections':sections,'count_label':'聊天教學・'+str(bubbles)+'則對話・'+str(tries)+'題換你',
  'prev':c['prev'],'next':c['next'],'figures':[]}
 (SRC/'units'/(ukey+'.json')).write_text(json.dumps(conf,ensure_ascii=False,indent=1),encoding='utf-8')
 (SRC/'units'/(ukey+'.questions.json')).write_text('[]',encoding='utf-8')
 (SRC/'units'/(ukey+'.html')).write_text('<!-- Generated by _src/build_chat_4.py from _src/chat/; edit the fragments, not this file. -->\n'+'\n'.join(body)+'\n',encoding='utf-8')
 build(ukey)
 print(ukey,'bubbles',bubbles,'tries',tries)

if __name__=='__main__':
 for s in sys.argv[1:] or ['earth','biology']:main(s)
